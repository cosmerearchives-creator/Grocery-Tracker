const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('grocery', {
  previewProduct: url => ipcRenderer.invoke('preview-product', url),
  onReviewProduct: callback => ipcRenderer.on('review-product', (_event, preview) => callback(preview)),
  importProduct: (url, category, options) => ipcRenderer.invoke('import-product', url, category, options),
  cancelImport: () => ipcRenderer.invoke('cancel-import'),
  onImport: callback => ipcRenderer.on('import-status', (_event, state) => callback(state)),
  listFile: (action, name) => ipcRenderer.invoke('list-file', action, name),
  load: () => ipcRenderer.invoke('load'),
  change: change => ipcRenderer.invoke('change', change),
  onCartChanged: callback => ipcRenderer.on('cart-changed', (_event, cart) => callback(cart)),
  stores: () => ipcRenderer.invoke('stores'),
  cartView: (selectedStore, comparisons) => ipcRenderer.invoke('cart-view', selectedStore, comparisons),
  emptyCarts: () => ipcRenderer.invoke('empty-carts'),
  refreshThumbnails: () => ipcRenderer.invoke('refresh-thumbnails'),
  refreshPrices: () => ipcRenderer.invoke('refresh-prices'),
  cancelPriceRefresh: () => ipcRenderer.invoke('cancel-price-refresh'),
  onPriceRefresh: callback => ipcRenderer.on('price-refresh-status', (_event, state) => callback(state)),
  openStore: store => ipcRenderer.invoke('open-store', store),
  searchStores: (query, itemId, choiceId) => ipcRenderer.invoke('search-stores', query, itemId, choiceId),
  searchStore: (store, itemId, choiceId) => ipcRenderer.invoke('search-store', store, itemId, choiceId),
  setCaptureTarget: itemId => ipcRenderer.invoke('capture-target', itemId),
  capture: (store, url) => ipcRenderer.invoke('capture', store, url),
  export: (store, kind) => ipcRenderer.invoke('export', store, kind),
  checkUpdate: () => ipcRenderer.invoke('check-update'),
  installUpdate: () => ipcRenderer.invoke('install-update'),
  onUpdate: callback => ipcRenderer.on('update-status', (_event, data) => callback(data))
});
